numero1 = int(input("Digite um numero "))
numero2 = int(input("Digite um numero "))

igual = numero1 == numero2
diferentes = numero1 != numero2
maior_que_o_segundo = numero1 > numero2
menor_que_o_segundo = numero1 < numero2
maior_igual_segundo = numero1 >= numero2
menor_igual_segundo = numero1 <= numero2

print(f"igual: {igual}")
print(f"diferentes: {diferentes}")
print(f"maior que o segundo: {maior_que_o_segundo}")
print(f"menor que o segundo: {menor_que_o_segundo}")
print(f"maior igual segundo: {maior_igual_segundo}")
print(f"menor igual segundo: {menor_igual_segundo}")